func fixture(t *testing.T, files map[string]string) string {
	t.Helper()
	dir := t.TempDir()
	files["go.mod"] = "module example.com/sample\n\ngo 1.26.0\n"
	for name, content := range files {
		path := filepath.Join(dir, name)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

func read(t *testing.T, dir, name string) []byte {
	t.Helper()
	data, err := os.ReadFile(filepath.Join(dir, name))
	if err != nil {
		t.Fatal(err)
	}
	return data
}

func TestPipeline(t *testing.T) {
	source := "package sample\ntype S struct{ A, B, C int }\nfunc f(a,b,c bool) S {\n\nif a && b && c { return S{1,2,3} }; return S{}\n\n}\n"
	plain := "package sample\nfunc plain() {\n\n}\n"
	generated := "// Code generated by fixture. DO NOT EDIT.\npackage sample\nvar generated= S{1,2,3}\n"
	dir := fixture(t, map[string]string{
		"sample.go":         source,
		"plain.go":          plain,
		"generated.go":      generated,
		"sample_test.go":    "package sample_test\nimport s \"example.com/sample\"\nvar _=s.Value{1,2,3}\n",
		"value.go":          "package sample\ntype Value struct{ A,B,C int }\n",
		"nested/go.mod":     "module example.com/nested\ngo 1.26.0\n",
		"nested/broken.go":  "not Go",
		"vendor/ignored.go": "package ignored\nvar V=1\n",
	})
	before := read(t, dir, "sample.go")
	paths, err := Run(t.Context(), Options{Dir: dir})
	if err != nil || len(paths) != 4 {
		t.Fatalf("check: %v, %v", paths, err)
	}
	if !bytes.Equal(before, read(t, dir, "sample.go")) {
		t.Fatal("check mode wrote source")
	}
	if err := os.Chmod(filepath.Join(dir, "sample.go"), 0o640); err != nil {
		t.Fatal(err)
	}
	if _, err := Run(t.Context(), Options{Dir: dir, Write: true}); err != nil {
		t.Fatal(err)
	}
	want := "package sample\n\ntype S struct{ A, B, C int }\n\nfunc f(a, b, c bool) S {\n\tif a &&\n\t\tb &&\n\t\tc {\n\t\treturn S{\n\t\t\t1,\n\t\t\t2,\n\t\t\t3,\n\t\t}\n\t}\n\treturn S{}\n}\n"
	if got := string(read(t, dir, "sample.go")); got != want {
		t.Fatalf("pipeline output:\n%s\nwant:\n%s", got, want)
	}
	if got := string(read(t, dir, "plain.go")); got != "package sample\n\nfunc plain() {\n}\n" {
		t.Fatalf("gofumpt without layout edits: %q", got)
	}
	if got := string(read(t, dir, "generated.go")); got != generated {
		t.Fatal("generated file modified")
	}
	if got := string(read(t, dir, "vendor/ignored.go")); got != "package ignored\nvar V=1\n" {
		t.Fatal("vendor file modified")
	}
	if got := string(read(t, dir, "sample_test.go")); got != "package sample_test\n\nimport s \"example.com/sample\"\n\nvar _ = s.Value{\n\t1,\n\t2,\n\t3,\n}\n" {
		t.Fatalf("external test package: %s", got)
	}
	stat, err := os.Stat(filepath.Join(dir, "sample.go"))
	if err != nil || stat.Mode().Perm() != 0o640 {
		t.Fatalf("file permissions: %v, %v", stat, err)
	}
	paths, err = Run(t.Context(), Options{Dir: dir})
	if err != nil || len(paths) != 0 {
		t.Fatalf("not idempotent: %v, %v", paths, err)
	}
}

func TestLoadErrorDoesNotWrite(t *testing.T) {
	for _, broken := range []string{"package sample\nvar _ = missing\n", "package sample\nfunc {"} {
		dir := fixture(t, map[string]string{"good.go": "package sample\nvar A=1\n", "broken.go": broken})
		before := read(t, dir, "good.go")
		_, err := Run(t.Context(), Options{Dir: dir, Write: true})
		if err == nil || !strings.Contains(err.Error(), "load or type errors") {
			t.Fatalf("expected load error: %v", err)
		}
		if !bytes.Equal(before, read(t, dir, "good.go")) {
			t.Fatal("modified good file before reporting load error")
		}
	}
}

func TestTagsAndPatterns(t *testing.T) {
	dir := fixture(t, map[string]string{
		"base.go":    "package sample\n",
		"tagged.go":  "//go:build special\n\npackage sample\nvar Tagged=1\n",
		"sub/sub.go": "package sub\nvar V=1\n",
	})
	paths, err := Run(t.Context(), Options{Dir: dir, Patterns: []string{"."}})
	if err != nil || len(paths) != 0 {
		t.Fatalf("default tags/pattern: %v, %v", paths, err)
	}
	paths, err = Run(t.Context(), Options{
		Dir:      dir,
		Patterns: []string{"."},
		Tags:     "special",
	})
	if err != nil ||
		len(paths) != 1 ||
		filepath.Base(paths[0]) != "tagged.go" {
		t.Fatalf("explicit tags: %v, %v", paths, err)
	}
	if _, err := Run(t.Context(), Options{Dir: dir, Patterns: []string{"./absent/..."}}); err == nil {
		t.Fatal("unmatched pattern succeeded")
	}
}

func TestCanceled(t *testing.T) {
	ctx, cancel := context.WithCancel(t.Context())
	cancel()
	dir := fixture(t, map[string]string{"sample.go": "package sample\n"})
	if _, err := Run(ctx, Options{Dir: dir}); err == nil {
		t.Fatal("canceled run succeeded")
	}
}

func TestWriteFileRejectsChangedInput(t *testing.T) {
	dir := fixture(t, map[string]string{"sample.go": "new content"})
	err := writeFile(change{
		path:   filepath.Join(dir, "sample.go"),
		source: []byte("old content"),
		output: []byte("formatted"),
		mode:   0o644,
	})
	if err == nil || string(read(t, dir, "sample.go")) != "new content" {
		t.Fatalf("concurrent edit not preserved: %v", err)
	}
}

func TestModuleLanguageAndDefaultRules(t *testing.T) {
	for _, version := range []string{"1.12", "1.26.0"} {
		t.Run(version, func(t *testing.T) {
			dir := fixture(t, map[string]string{
				"sample.go": "package sample\nconst Mode = 0755\nfunc F(a int, b int) (result int) { return }\n",
			})
			if err := os.WriteFile(filepath.Join(dir, "go.mod"), []byte("module example.com/sample\n\ngo "+version+"\n"), 0o644); err != nil {
				t.Fatal(err)
			}
			if _, err := Run(t.Context(), Options{Dir: dir, Write: true}); err != nil {
				t.Fatal(err)
			}
			wantMode := "0755"
			if version == "1.26.0" {
				wantMode = "0o755"
			}
			want := "package sample\n\nconst Mode = " + wantMode + "\n\nfunc F(a int, b int) (result int) { return }\n"
			if got := string(read(t, dir, "sample.go")); got != want {
				t.Fatalf("module language/default extra rules:\n%s\nwant:\n%s", got, want)
			}
		})
	}
}

func TestSymlinkWriteDoesNotReplaceLink(t *testing.T) {
	dir := fixture(t, map[string]string{"sample.go": "package sample\nvar Value=1\n"})
	original := read(t, dir, "sample.go")
	target := filepath.Join(t.TempDir(), "target.go")
	if err := os.Rename(filepath.Join(dir, "sample.go"), target); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(target, filepath.Join(dir, "sample.go")); err != nil {
		t.Fatal(err)
	}
	if _, err := Run(t.Context(), Options{Dir: dir}); err != nil {
		t.Fatal(err)
	}
	if _, err := Run(t.Context(), Options{Dir: dir, Write: true}); err == nil || !strings.Contains(err.Error(), "non-regular file") {
		t.Fatalf("expected symlink refusal: %v", err)
	}
	if !bytes.Equal(original, read(t, dir, "sample.go")) {
		t.Fatal("symlink target changed")
	}
	if _, err := os.Readlink(filepath.Join(dir, "sample.go")); err != nil {
		t.Fatalf("symlink was replaced: %v", err)
	}
}
